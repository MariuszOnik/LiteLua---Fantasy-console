# LiteLua - writes source/ll_chiptest_song.inc for the S0 hardware test
# (D40): pattern "a" of examples/songs/sky_hopper.lsong as C arrays. At 150
# BPM and ppq 24 one tick is exactly 1/60 s, so the ticks are used as frames.
#
#   python tools/make_chiptest_song.py

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import lsong  # noqa: E402

DRUM = {36: 0, 38: 1, 42: 2}  # kick, snare, hat


def main():
    song = lsong.load(ROOT / "examples/songs/sky_hopper.lsong")
    assert song["tempo"] == 150 and song["ppq"] == 24, "ticks must be 1/60 s"
    pat = song["patterns"]["a"]
    out = ["// Generated by tools/make_chiptest_song.py from examples/songs/sky_hopper.lsong",
           "// (pattern a). Notes: start frame, length in frames, MIDI pitch, flag.",
           f"#define CHIP_SONG_LENGTH {pat['length']}", ""]

    def table(name, notes, flag):
        rows = [f"    {{ {n['t']}, {n['d']}, {n['p']}, {flag(n)} }}," for n in notes]
        out.append(f"static const ChipNote {name}[] = {{")
        out.extend(rows)
        out.append("};")
        out.append("")

    notes = pat["notes"]
    table("song_lead", notes["lead"], lambda n: 0)
    table("song_chords", notes["chords"], lambda n: 1 if n.get("i") == "chord_min" else 0)
    table("song_bass", notes["bass"], lambda n: 0)
    table("song_drums", notes["drums"], lambda n: DRUM[n["p"]])
    ins = song["instruments"]
    for name in ("lead", "chord_maj"):
        env = ", ".join(str(round(v * 127)) for v in ins[name]["env"])
        out.append(f"static const u8 env_{name}[] = {{ {env} }};")
    path = ROOT / "source/ll_chiptest_song.inc"
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(path.relative_to(ROOT), sum(len(v) for v in notes.values()), "notes")


if __name__ == "__main__":
    main()
