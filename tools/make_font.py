COLS, ROWS, CW, CH = 16, 8, 6, 8
W, H = COLS * CW, ROWS * CH  # 96 x 64


def chunk(kind, data):
    body = kind + data
    return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))


def main():
    assert len(ORDER) <= COLS * ROWS
    missing = [c for c in ORDER if c not in G]
    assert not missing, missing

    pixels = [[0] * W for _ in range(H)]
    for i, ch in enumerate(ORDER):
        cx, cy = (i % COLS) * CW, (i // COLS) * CH
        for y, row in enumerate(G[ch]):
            for x, p in enumerate(row):
                if p == "#":
                    pixels[cy + y][cx + x] = 1

    # 1-bit palette PNG: index 0 transparent (D10), index 1 white
    rows = []
    for y in range(H):
        bits = 0
        row = bytearray()
        for x in range(W):
            bits = (bits << 1) | pixels[y][x]
            if x % 8 == 7:
                row.append(bits)
                bits = 0
        rows.append(b"\x00" + bytes(row))
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 1, 3, 0, 0, 0))
    png += chunk(b"PLTE", bytes((0, 0, 0, 255, 255, 255)))
    png += chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
    png += chunk(b"IEND", b"")

    PNG_OUT.parent.mkdir(exist_ok=True)
    PNG_OUT.write_bytes(png)

    lines = [", ".join(f"0x{b:02x}" for b in png[i:i + 12]) for i in range(0, len(png), 12)]
    INC_OUT.write_text(
        "// Generated by tools/make_font.py from the glyphs in that script - do not edit.\n"
        f"// 6x8 font sheet, {COLS}x{ROWS} cells: ASCII 32-126, \"{POLISH}\", unknown.\n"
        "static const unsigned char font6x8_png[] = {\n    "
        + ",\n    ".join(lines) + "\n};\n", encoding="utf-8")
    print(f"{PNG_OUT.name}: {len(ORDER)} glyphs, {len(png)} bytes; {INC_OUT.name} written")


if __name__ == "__main__":
    main()
