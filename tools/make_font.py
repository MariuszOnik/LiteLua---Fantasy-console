# LiteLua - built-in 6x8 font (D8, D22): ASCII, Polish letters and a box for
# unknown characters. The glyphs below are the source; this script writes
#   assets/font6x8.png         the font sheet (16 x 8 cells of 6x8, 2 colors)
#   source/ll_font6x8.inc      the same PNG as a C byte array (built into the ROM)
#
# Cell layout (8 rows): capitals and digits use rows 1-6 (row 0 is for
# accents), lowercase letters rows 2-6, descenders and ogoneks row 7. Glyphs
# are 5 pixels wide; the 6th column is the space between characters.
#
# Usage: python tools/make_font.py

