def g(top, *rows):
    """A glyph: 'top' is the first row used, rows are 5-character strings."""
    out = ["....."] * 8
    for i, r in enumerate(rows):
        assert len(r) == 5, r
        out[top + i] = r
    return out


def accent(base, row):
    out = list(base)
    out[0] = row
    return out


def accent2(base, row0, row1):
    out = list(base)
    out[0], out[1] = row0, row1
    return out


def ogonek(base, row):
    out = list(base)
    out[7] = row
    return out


