// LiteLua - built-in demo used when there is no main.lua on the SD card.
// Tests the P1 core: callbacks, frame rate, input, error screen and the
// Lua memory limit. Text goes to the console on the bottom screen.

const char ll_demo_lua[] =
    "local frame, fps, fcount, t0 = 0, 0, 0, micros()\n"
    "local draws = { [TOP] = 0, [BOTTOM] = 0 }\n"
    "local names = { 'a', 'b', 'x', 'y', 'l', 'r', 'start', 'select',\n"
    "                'up', 'down', 'left', 'right', 'touch' }\n"
    "local last_p, last_r = '-', '-'\n"
    "\n"
    "local function at(row, fmt, ...)\n"
    "  io.write(('\\27[%d;0H%-31s'):format(row, fmt:format(...)))\n"
    "end\n"
    "\n"
    "function _init()\n"
    "  io.write('\\27[2J')\n"
    "  at(0, 'LiteLua P1 demo')\n"
    "  at(15, 'SELECT: error screen test')\n"
    "  at(16, 'L+R:    out of memory test')\n"
    "  at(17, 'Y:      error inside a function')\n"
    "end\n"
    "\n"
    "local function nested() local t = nil; return t.field end\n"
    "\n"
    "function _update()\n"
    "  frame = frame + 1\n"
    "  fcount = fcount + 1\n"
    "  local t = micros()\n"
    "  if t - t0 >= 1000000 or t < t0 then fps, fcount, t0 = fcount, 0, t end\n"
    "  for _, n in ipairs(names) do\n"
    "    if btnp(n) then last_p = n end\n"
    "    if btnr(n) then last_r = n end\n"
    "  end\n"
    "  if btnp('select') then error('test error (SELECT pressed)') end\n"
    "  if btnp('y') then nested() end\n"
    "  if btn('l') and btn('r') then\n"
    "    local hog = {}\n"
    "    while true do hog[#hog + 1] = ('x'):rep(1000) .. #hog end\n"
    "  end\n"
    "end\n"
    "\n"
    "function _draw(screen)\n"
    "  draws[screen] = draws[screen] + 1\n"
    "  if screen ~= BOTTOM then return end\n"
    "  local held = {}\n"
    "  for _, n in ipairs(names) do if btn(n) then held[#held + 1] = n end end\n"
    "  local tx, ty = touch()\n"
    "  at(2, 'frame %d  fps %d', frame, fps)\n"
    "  at(3, 'draw top %d bottom %d', draws[TOP], draws[BOTTOM])\n"
    "  at(5, 'held: %s', table.concat(held, ' '))\n"
    "  at(6, 'last pressed:  %s', last_p)\n"
    "  at(7, 'last released: %s', last_r)\n"
    "  at(8, 'touch: %s', tx and (tx .. ', ' .. ty) or '-')\n"
    "  at(10, 'Lua mem: %d KB', collectgarbage('count') // 1)\n"
    "end\n";
