// LiteLua - built-in demo, the first entry of the cart list. Tests the core:
// callbacks on both screens, frame rate, input, touch, the error screen and
// the Lua memory limit.

const char ll_demo_lua[] =
    "local frame, fps, fcount, t0 = 0, 0, 0, micros()\n"
    "local draws = { [TOP] = 0, [BOTTOM] = 0 }\n"
    "local names = { 'a', 'b', 'x', 'y', 'l', 'r', 'start', 'select',\n"
    "                'up', 'down', 'left', 'right', 'touch' }\n"
    "local last_p, last_r = '-', '-'\n"
    "local trail = {}\n"
    "\n"
    "local function nested() local t = nil; return t.field end\n"
    "\n"
    "function _update()\n"
    "  frame = frame + 1\n"
    "  fcount = fcount + 1\n"
    "  local t = micros()\n"
    "  if t - t0 >= 1000000 or t < t0 then fps, fcount, t0 = fcount, 0, t end\n"
    "  for _, n in ipairs(names) do\n"
    "    if btnp(n) then last_p = n end\n"
    "    if btnr(n) then last_r = n end\n"
    "  end\n"
    "  if btnp('a') then print('A pressed in frame ' .. frame) end\n"
    "  if btnp('b') then log('B pressed in frame ' .. frame) end\n"
    "  if btnp('select') then error('test error (SELECT pressed)') end\n"
    "  if btnp('up') then nested() end\n"
    "  if btnp('down') then\n"
    "    local hog = {}\n"
    "    while true do hog[#hog + 1] = ('x'):rep(1000) .. #hog end\n"
    "  end\n"
    "  local tx, ty = touch()\n"
    "  if tx then\n"
    "    trail[#trail + 1] = { tx, ty }\n"
    "    if #trail > 40 then table.remove(trail, 1) end\n"
    "  end\n"
    "end\n"
    "\n"
    "function _draw(screen)\n"
    "  draws[screen] = draws[screen] + 1\n"
    "  if screen == TOP then\n"
    "    cls(1)\n"
    "    rectfill(0, 0, 256, 12, 8)\n"
    "    text('LiteLua demo', 4, 2, 4)\n"
    "    text(('frame %d   fps %d'):format(frame, fps), 4, 20, 12)\n"
    "    text(('draws: top %d  bottom %d'):format(draws[TOP], draws[BOTTOM]), 4, 30, 12)\n"
    "    local held = {}\n"
    "    for _, n in ipairs(names) do if btn(n) then held[#held + 1] = n end end\n"
    "    text('held: ' .. table.concat(held, ' '), 4, 46, 5)\n"
    "    text('last pressed:  ' .. last_p, 4, 56, 13)\n"
    "    text('last released: ' .. last_r, 4, 66, 13)\n"
    "    text(('Lua mem: %d KB'):format(collectgarbage('count') // 1), 4, 82, 13)\n"
    "    local x = 128 + math.sin(frame / 20) * 100\n"
    "    circfill(x, 120, 10, 10)\n"
    "    text('A: print   B: log', 4, 144, 14)\n"
    "    text('SELECT: error   Up: error in a function', 4, 154, 14)\n"
    "    text('Down: out of memory', 4, 164, 14)\n"
    "    text('L+R+B: list  L+R+Y: stats  L+R+X: console', 4, 180, 14)\n"
    "  else\n"
    "    cls(15)\n"
    "    text('Touch the screen', 4, 4, 13)\n"
    "    for i, p in ipairs(trail) do\n"
    "      circfill(p[1], p[2], 1 + i // 8, i % 15 + 1)\n"
    "    end\n"
    "    local tx, ty = touch()\n"
    "    if tx then\n"
    "      circ(tx, ty, 12, 12)\n"
    "      text(tx .. ', ' .. ty, 4, 180, 12)\n"
    "    end\n"
    "  end\n"
    "end\n";
