r"""Makes the C4 battle cart (HeroesDS/carts/c4) and copies it to the emulator SD card.

  python HeroesDS/tools/make_c4.py [--sd D:\Programowanie\sdcard] [--gfx] [--force]
                                   [--lcart out.lcart]

The cart gets the combat engine and the rules (cartkit); main.lua and src/ are ours.
--gfx converts the creatures' and heroes' combat animations from the original game
(Data/) in the STYLE style at the field's scale 3/16 (H5, H8): for every actor the
states in STATES, 8 directions each, as gfx/u/<actor>_<state>_<dir>.png (+ _sh.png, the
shadow) and data/anim/<actor>_<state>.lua = { [dir] = meta } (h4atlas meta). Made
animations are kept unless --force. gfx/ and data/ stay out of git (H1).
The cart goes to the SD card as one file, litelua/carts/c4.lcart (a ZIP without
compression: the PNGs are compressed already), not as ~6000 files; --lcart also writes it
elsewhere (for the console over FTP).
"""
import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cartkit  # noqa: E402

CART = cartkit.cart_dir("c4")
DATA = os.path.join(cartkit.HEROES, "Data")
STATES = ("wait", "walk", "melee", "flinch", "die")
DIRS = ("e", "n", "ne", "nw", "s", "se", "sw", "w")
SCALE = 0.1875
STYLE = "test2"   # tools/styles.json, tuned by the user in style_tuner.py
# the hero types of src/setup.lua (school x role)
HERO_ACTORS = tuple(f"hero.{s}_{r}_male" for s in ("life", "order", "death", "chaos", "nature", "might")
                    for r in ("fighter", "archer", "mage") if (s, r) != ("might", "mage"))


def file_name(actor):
    return re.sub(r"[^a-z0-9]+", "_", actor.lower()).strip("_")


def actors():
    with open(os.path.join(cartkit.RULES, "creatures.lua"), encoding="utf-8") as f:
        keys = re.findall(r'^  \["([^"]+)"\]', f.read(), re.M)
    return sorted(keys) + list(HERO_ACTORS)


def make_gfx(force, todo=None, states=STATES):
    import h4atlas
    import h4r
    lib = h4r.Library(DATA)
    gfx = os.path.join(CART, "gfx", "u")
    meta_dir = os.path.join(CART, "data", "anim")
    os.makedirs(gfx, exist_ok=True)
    os.makedirs(meta_dir, exist_ok=True)
    made = skipped = 0
    for actor in todo or actors():
        base = file_name(actor)
        for state in states:
            meta_path = os.path.join(meta_dir, f"{base}_{state}.lua")
            if os.path.exists(meta_path) and not force:
                skipped += 1
                continue
            metas = {}
            for d in DIRS:
                try:
                    atlas, shadow, meta = h4atlas.convert(lib, actor, state, d, SCALE, style=STYLE)
                except (ValueError, KeyError) as e:
                    print(f"  {actor} {state} {d}: {e}")
                    continue
                if atlas is None:   # no frame drawn in this direction
                    continue
                name = f"{base}_{state}_{d}"
                atlas.save(os.path.join(gfx, name + ".png"), optimize=True)
                meta["image"] = "u/" + name
                meta["shadow"] = False
                if shadow:
                    shadow.save(os.path.join(gfx, name + "_sh.png"), optimize=True)
                    meta["shadow"] = "u/" + name + "_sh"
                metas[d] = meta
            with open(meta_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(f"-- {actor} {state}: generated by HeroesDS/tools/make_c4.py from the original game\n")
                f.write("return {\n")
                for d, m in metas.items():
                    f.write(f"  {d} = {h4atlas.lua(m)},\n")
                f.write("}\n")
            made += 1
        print(f"  {actor}")
    print(f"  animations: {made} made, {skipped} kept")


def make_fx(force):
    """Missiles (as actors: walk in 8 directions), spell effects (gfx/fx, data/fx), sounds
    (sfx/<actor>_<melee|ranged|flinch|die|walk>.wav, sfx/spell_<spell>.wav) and data/actors.lua: each actor's
    height (screen pixels at SCALE, where effects hang) and missile."""
    import h4actor
    import h4atlas
    import h4fx
    import h4r
    lib = h4r.Library(DATA)
    missiles = sorted(set(h4fx.MISSILES.values()) | {"arrow", "magic"})
    make_gfx(force, [f"missile.{m}" for m in missiles], ("walk",))
    # data/actors.lua
    rows = []
    for actor in actors() + [f"missile.{m}" for m in missiles]:
        res = f"combat_actor.{actor}.h4d"
        a = h4actor.parse(lib.read(res), res)
        missile = h4fx.MISSILES.get(actor.lower())
        if actor.startswith("hero."):
            missile = "magic" if "_mage_" in actor.lower() else "arrow"
        m = f', missile = "missile_{missile}"' if missile else ""
        rows.append(f'  {file_name(actor)} = {{ height = {round(a["height"] * SCALE)}{m} }},')
    with open(os.path.join(CART, "data", "actors.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Actors' heights and missiles: made by HeroesDS/tools/make_c4.py from the original game\n")
        f.write("return {\n" + "\n".join(rows) + "\n}\n")
    # spell effects
    with open(os.path.join(cartkit.RULES, "spells.lua"), encoding="utf-8") as f:
        spells = sorted(re.findall(r'^  \["([^"]+)"\]', f.read(), re.M)) + ["magic resistance"]
    os.makedirs(os.path.join(CART, "gfx", "fx"), exist_ok=True)
    os.makedirs(os.path.join(CART, "data", "fx"), exist_ok=True)
    made = 0
    for key in spells:
        base = file_name(key)
        meta_path = os.path.join(CART, "data", "fx", base + ".lua")
        if os.path.exists(meta_path) and not force:
            continue
        r = h4fx.convert_effect(lib, key, SCALE, STYLE)
        if not r:
            continue
        atlas, meta = r
        atlas.save(os.path.join(CART, "gfx", "fx", base + ".png"), optimize=True)
        meta["image"], meta["shadow"] = "fx/" + base, False
        with open(meta_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"-- animation.spell.{key}: generated by HeroesDS/tools/make_c4.py from the original game\n")
            f.write("return " + h4atlas.lua(meta) + "\n")
        made += 1
    print(f"  spell effects: {made} made")
    # sounds
    sfx = os.path.join(CART, "sfx")
    os.makedirs(sfx, exist_ok=True)
    made = 0
    jobs = [(f"sound.{a}.{st}.h4d", f"{file_name(a)}_{st}") for a in actors()
            for st in ("melee", "ranged", "flinch", "die", "walk")]
    jobs += [(f"sound.spell.{k}.h4d", f"spell_{file_name(k)}") for k in spells]
    for res, name in jobs:
        out = os.path.join(sfx, name + ".wav")
        if res not in lib or (os.path.exists(out) and not force):
            continue
        with open(out, "wb") as f:
            f.write(h4fx.wav(lib.read(res)))
        made += 1
    print(f"  sounds: {made} made")


def write_style():
    """data/style.lua: what the cart needs of the style (the field's colour = its ground)"""
    import h4atlas
    st = h4atlas.STYLES[STYLE]
    r, g, b = st.ground
    with open(os.path.join(CART, "data", "style.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"-- The graphics' style ({STYLE}, tools/styles.json): made by HeroesDS/tools/make_c4.py\n")
        f.write(f'return {{ name = "{STYLE}", ground = 0x{r:02x}{g:02x}{b:02x} }}\n')


def main(argv):
    p = argparse.ArgumentParser()
    p.add_argument("--sd", default=cartkit.SD)
    p.add_argument("--gfx", action="store_true", help="convert the animations")
    p.add_argument("--fx", action="store_true", help="convert missiles, spell effects and sounds")
    p.add_argument("--force", action="store_true", help="convert again the ones made")
    p.add_argument("--lcart", help="also pack the cart into this .lcart file")
    a = p.parse_args(argv[1:])
    cartkit.copy_engine(CART)
    cartkit.copy_rules(CART, ("creatures.lua", "spells.lua", "artifacts.lua"))
    write_style()
    if a.gfx:
        make_gfx(a.force)
    if a.fx:
        make_fx(a.force)
    tool = os.path.join(cartkit.HEROES, "..", "tools", "litelua.py")
    outs = [a.lcart] if a.lcart else []
    if a.sd and os.path.isdir(a.sd):
        outs.append(os.path.join(a.sd, "litelua", "carts", "c4.lcart"))
    for out in outs:
        subprocess.run([sys.executable, tool, "pack", CART, out, "--store"], check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
