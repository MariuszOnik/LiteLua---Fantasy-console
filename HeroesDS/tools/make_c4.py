r"""Makes the C4 battle cart (HeroesDS/carts/c4) and copies it to the emulator SD card.

  python HeroesDS/tools/make_c4.py [--sd D:\Programowanie\sdcard] [--gfx] [--force]
                                   [--lcart out.lcart]

The cart gets the combat engine and the rules (cartkit); main.lua and src/ are ours.
--gfx converts the creatures' and heroes' combat animations from the original game
(Data/) in the "test1" style at the field's scale 3/16 (H5, H8): for every actor the
states in STATES, 8 directions each, as gfx/u/<actor>_<state>_<dir>.png (+ _sh.png, the
shadow) and data/anim/<actor>_<state>.lua = { [dir] = meta } (h4atlas meta). Made
animations are kept unless --force. gfx/ and data/ stay out of git (H1).
The cart goes to the SD card as one file, litelua/carts/c4.lcart (a ZIP without
compression: the PNGs are compressed already), not as ~6000 files; --lcart also writes it
elsewhere (for the console over FTP).
"""
import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cartkit  # noqa: E402

CART = cartkit.cart_dir("c4")
DATA = os.path.join(cartkit.HEROES, "Data")
STATES = ("wait", "walk", "melee", "flinch", "die")
DIRS = ("e", "n", "ne", "nw", "s", "se", "sw", "w")
SCALE = 0.1875
STYLE = "test1"
# the heroes of src/setup.lua
HERO_ACTORS = ("hero.life_fighter_male", "hero.death_mage_female")


def file_name(actor):
    return re.sub(r"[^a-z0-9]+", "_", actor.lower()).strip("_")


def actors():
    with open(os.path.join(cartkit.RULES, "creatures.lua"), encoding="utf-8") as f:
        keys = re.findall(r'^  \["([^"]+)"\]', f.read(), re.M)
    return sorted(keys) + list(HERO_ACTORS)


def make_gfx(force):
    import h4atlas
    import h4r
    lib = h4r.Library(DATA)
    gfx = os.path.join(CART, "gfx", "u")
    meta_dir = os.path.join(CART, "data", "anim")
    os.makedirs(gfx, exist_ok=True)
    os.makedirs(meta_dir, exist_ok=True)
    made = skipped = 0
    for actor in actors():
        base = file_name(actor)
        for state in STATES:
            meta_path = os.path.join(meta_dir, f"{base}_{state}.lua")
            if os.path.exists(meta_path) and not force:
                skipped += 1
                continue
            metas = {}
            for d in DIRS:
                try:
                    atlas, shadow, meta = h4atlas.convert(lib, actor, state, d, SCALE, style=STYLE)
                except (ValueError, KeyError) as e:
                    print(f"  {actor} {state} {d}: {e}")
                    continue
                name = f"{base}_{state}_{d}"
                atlas.save(os.path.join(gfx, name + ".png"), optimize=True)
                meta["image"] = "u/" + name
                meta["shadow"] = False
                if shadow:
                    shadow.save(os.path.join(gfx, name + "_sh.png"), optimize=True)
                    meta["shadow"] = "u/" + name + "_sh"
                metas[d] = meta
            with open(meta_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(f"-- {actor} {state}: generated by HeroesDS/tools/make_c4.py from the original game\n")
                f.write("return {\n")
                for d, m in metas.items():
                    f.write(f"  {d} = {h4atlas.lua(m)},\n")
                f.write("}\n")
            made += 1
        print(f"  {actor}")
    print(f"  animations: {made} made, {skipped} kept")


def main(argv):
    p = argparse.ArgumentParser()
    p.add_argument("--sd", default=cartkit.SD)
    p.add_argument("--gfx", action="store_true", help="convert the animations")
    p.add_argument("--force", action="store_true", help="convert again the ones made")
    p.add_argument("--lcart", help="also pack the cart into this .lcart file")
    a = p.parse_args(argv[1:])
    cartkit.copy_engine(CART)
    cartkit.copy_rules(CART)
    if a.gfx:
        make_gfx(a.force)
    tool = os.path.join(cartkit.HEROES, "..", "tools", "litelua.py")
    outs = [a.lcart] if a.lcart else []
    if a.sd and os.path.isdir(a.sd):
        outs.append(os.path.join(a.sd, "litelua", "carts", "c4.lcart"))
    for out in outs:
        subprocess.run([sys.executable, tool, "pack", CART, out, "--store"], check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
